-- 36 · Veredas del proyecto ZAP (Instituto Humboldt) en el Caquetá
-- ---------------------------------------------------------------------
-- La capa de veredas de la geodatabase ZAP_zonificacion es la que usó el
-- Instituto: 137 de las 138 veredas «de campo» del Caquetá existen en
-- ella con ese nombre. Esta carga:
--   · agrega a vereda el núcleo ZAP y el origen 'zap';
--   · a cada vereda ZAP le busca su registro en el municipio (mismo
--     nombre sin tildes, mayúsculas ni espacios), prefiriendo la oficial;
--   · si la encontrada es de campo, la marca como ZAP y validada;
--   · si hay otra vereda de campo con el mismo nombre, pasa sus predios a
--     la encontrada y borra la repetida;
--   · crea las veredas ZAP que no estaban, validadas.
-- 390 veredas de 8 municipios (Florencia, Belén, El Paujil, Milán, Morelia,
-- San José del Fragua, San Vicente del Caguán y Solita).
-- =====================================================================

