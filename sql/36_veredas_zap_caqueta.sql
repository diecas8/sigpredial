declare z record; v_dest uuid; v_mov int := 0; v_borr int := 0; v_nuevas int := 0; v_camp int := 0; v_ofi int := 0; n int; v_esofi boolean;
begin
  for z in select * from zap_vereda where productores.f_normalizar(nombre) <> 'sin informacion' loop
    -- registro de destino: la oficial primero, luego la ZAP, luego la de campo con más predios
    select v.id into v_dest from productores.vereda v
     where v.cod_mpio = z.cod_mpio
       and replace(productores.f_normalizar(v.nombre), ' ', '') = replace(productores.f_normalizar(z.nombre), ' ', '')
     order by (v.origen = 'oficial') desc, (v.origen = 'zap') desc,
              (select count(*) from productores.predio p where p.vereda_id = v.id) desc, v.creado_en
     limit 1;
    if v_dest is null then
      insert into productores.vereda (nombre, cod_mpio, origen, validada, nucleo)
      values (case when z.nombre = upper(z.nombre) then initcap(lower(z.nombre)) else z.nombre end,
              z.cod_mpio, 'zap', true, z.nucleo);
      v_nuevas := v_nuevas + 1;
      continue;
    end if;
    -- veredas de campo repetidas: sus predios pasan al destino y se borran
    update productores.predio p set vereda_id = v_dest
     where p.vereda_id in (select v.id from productores.vereda v
                            where v.cod_mpio = z.cod_mpio and v.id <> v_dest and v.origen = 'campo'
                              and replace(productores.f_normalizar(v.nombre), ' ', '') = replace(productores.f_normalizar(z.nombre), ' ', ''));
    get diagnostics n = row_count; v_mov := v_mov + n;
    delete from productores.vereda v
     where v.cod_mpio = z.cod_mpio and v.id <> v_dest and v.origen = 'campo'
       and replace(productores.f_normalizar(v.nombre), ' ', '') = replace(productores.f_normalizar(z.nombre), ' ', '')
       and not exists (select 1 from productores.predio p where p.vereda_id = v.id);
    get diagnostics n = row_count; v_borr := v_borr + n;
    update productores.vereda set nucleo = coalesce(z.nucleo, nucleo),
           origen = case when origen = 'campo' then 'zap' else origen end,
           validada = true
     where id = v_dest
    returning (origen = 'oficial') into v_esofi;
    if v_esofi then v_ofi := v_ofi + 1; else v_camp := v_camp + 1; end if;
  end loop;
  raise notice 'Veredas ZAP: % oficiales con núcleo, % de campo reconocidas, % nuevas; % predios movidos, % repetidas borradas',
    v_ofi, v_camp, v_nuevas, v_mov, v_borr;
end $$;
